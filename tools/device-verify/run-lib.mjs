/**
 * dsh-device-verify · driver-side helpers (Node, no side effects on import).
 *
 * Everything the CLI needs that can be tested without adb or a phone lives here:
 * argument parsing, scenario/config merging, injection assembly, the report sink
 * and report decoding. run.mjs is then a thin adb wrapper around these.
 */
import { readFileSync } from 'node:fs'
import { createServer } from 'node:http'

/**
 * Load overlay-lib.js the same way the browser does (it is a classic script that
 * attaches itself to `globalThis`).
 * @param {string} filePath
 * @returns {object} the DshVerifyLib namespace
 */
export function loadOverlayLib(filePath) {
  const source = readFileSync(filePath, 'utf8')
  const factory = new Function(`${source}\nreturn globalThis.DshVerifyLib`) // eslint-disable-line no-new-func
  const lib = factory()
  if (lib === undefined || typeof lib.buildReport !== 'function') {
    throw new Error(`overlay-lib.js did not expose DshVerifyLib: ${filePath}`)
  }
  return lib
}

/**
 * `command --key value --flag` → { command, options, positional }.
 * `--key=value` is accepted too. A trailing flag without a value becomes "true".
 */
export function parseArgs(argv) {
  const tokens = Array.isArray(argv) ? argv : []
  // F2: a leading option (`smoke.mjs --gateway …`) is not a command. Treating it
  // as one silently dropped the URL and the run fell back to the admin status.
  const first = tokens[0]
  const hasCommand = typeof first === 'string' && first.startsWith('--') === false
  const command = hasCommand ? first : undefined
  const rest = hasCommand ? tokens.slice(1) : tokens
  const options = {}
  const positional = []
  for (let index = 0; index < rest.length; index += 1) {
    const item = rest[index]
    if (typeof item !== 'string') continue
    if (item.startsWith('--')) {
      const body = item.slice(2)
      const equals = body.indexOf('=')
      if (equals > 0) {
        options[body.slice(0, equals)] = body.slice(equals + 1)
        continue
      }
      const next = rest[index + 1]
      if (next !== undefined && (typeof next !== 'string' || next.startsWith('--') === false)) {
        options[body] = next
        index += 1
      } else {
        options[body] = 'true'
      }
      continue
    }
    positional.push(item)
  }
  return { command, options, positional }
}

/**
 * Read a config file and drop documentation-only keys.
 * @param {string} filePath
 */
export function loadConfig(filePath) {
  const parsed = JSON.parse(readFileSync(filePath, 'utf8'))
  if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error(`config must be a JSON object: ${filePath}`)
  }
  const { $comment, $schema, ...config } = parsed
  void $comment
  void $schema
  return config
}

/**
 * Apply CLI overrides to a config object (never mutating the input).
 * @param {object} config
 * @param {Record<string, string>} options parsed CLI options
 */
export function mergeCli(config, options) {
  const base = config !== null && typeof config === 'object' ? config : {}
  const merged = { ...base }
  const opts = options ?? {}

  if (opts.scenarios !== undefined) {
    const wanted = String(opts.scenarios).split(',').map(item => item.trim()).filter(item => item !== '')
    const known = new Map((Array.isArray(base.scenarios) ? base.scenarios : []).map(item => [item.name, item]))
    merged.scenarios = wanted.map(name => known.get(name) ?? { name, panel: name, labels: [name] })
  }

  const port = opts.port === undefined ? null : Number(opts.port)
  if (opts.sink !== undefined) {
    merged.sinkUrl = opts.sink === 'off' || opts.sink === 'false' ? null : String(opts.sink)
  } else if (port !== null && Number.isFinite(port) && port > 0) {
    merged.sinkUrl = `http://127.0.0.1:${Math.round(port)}/report`
  }

  for (const key of ['timeoutMs', 'pollIntervalMs', 'settlePolls', 'titleMaxChars', 'hitCheckLimit', 'maxStates', 'startDelayMs']) {
    if (opts[key] === undefined) continue
    const value = Number(opts[key])
    if (Number.isFinite(value)) merged[key] = value
  }

  if (opts.autostart === 'false' || opts['no-autostart'] === 'true') merged.autoStart = false
  // `--no-pilot`: inject the overlay but do not drive the page (a finger can then
  // open the keyboard on the conversation view).
  if (opts['no-pilot'] === 'true' || opts.noPilot === 'true') {
    merged.noPilot = true
    merged.autoStart = false
  }
  if (opts['no-keyboard'] === 'true') merged.keyboardProbe = false
  return merged
}

export const INJECTION_MARKER = 'dsh-verify-overlay'

/**
 * The file written to <DSH_HOME>/mobile-access/mobile.js.
 * Order matters: config → library → overlay.
 */
export function buildInjection({ config, libSource, overlaySource }) {
  const header = [
    '/* dsh-device-verify overlay — generated by tools/device-verify/run.mjs.',
    ` * Marker: ${INJECTION_MARKER} (used to detect and restore our own file).`,
    ' * Remove with: node tools/device-verify/run.mjs overlay off',
    ' */',
    `window.__dvConfig = ${JSON.stringify(config ?? {}, null, 2)};`,
    '',
  ].join('\n')
  // The `;\n` separator is load-bearing: two adjacent IIFEs would parse as
  // `})(…)(function(){…})()` and throw "… is not a function" at load time.
  return `${header}\n${libSource}\n;\n${overlaySource}`
}

/**
 * A tiny HTTP sink the phone POSTs the report to over `adb reverse`.
 * CORS is open because the mobile page is an https origin talking to loopback.
 *
 * @returns {{server: import('node:http').Server, requests: object[], url: string, listen: () => Promise<{port: number, host: string}>, close: () => Promise<void>}}
 */
export function createSinkServer(options) {
  const port = options?.port ?? 8799
  const host = options?.host ?? '127.0.0.1'
  const maxBytes = options?.maxBytes ?? 4 * 1024 * 1024
  const onReport = typeof options?.onReport === 'function' ? options.onReport : () => {}
  const requests = []

  const cors = {
    'access-control-allow-origin': '*',
    'access-control-allow-methods': 'POST, GET, OPTIONS',
    'access-control-allow-headers': 'content-type',
    'access-control-allow-private-network': 'true',
    'access-control-max-age': '600',
    'cache-control': 'no-store',
  }

  const server = createServer((request, response) => {
    if (request.method === 'OPTIONS') {
      response.writeHead(204, cors)
      response.end()
      return
    }
    const url = new URL(request.url ?? '/', `http://${host}:${port}`)
    if (url.pathname !== '/report') {
      response.writeHead(404, cors)
      response.end('not found')
      return
    }
    if (request.method === 'GET') {
      response.writeHead(200, { ...cors, 'content-type': 'text/plain; charset=utf-8' })
      response.end(`dsh-device-verify sink · ${requests.length} report(s) received\n`)
      return
    }
    if (request.method !== 'POST') {
      response.writeHead(405, cors)
      response.end('method not allowed')
      return
    }
    const chunks = []
    let size = 0
    request.on('data', chunk => {
      size += chunk.length
      if (size > maxBytes) {
        request.destroy()
        return
      }
      chunks.push(chunk)
    })
    request.on('end', () => {
      const raw = Buffer.concat(chunks).toString('utf8')
      let parsed = null
      try {
        parsed = JSON.parse(raw)
      } catch {
        parsed = null
      }
      if (parsed === null) {
        response.writeHead(400, cors)
        response.end('bad json')
        return
      }
      response.writeHead(204, cors)
      response.end()
      const entry = {
        at: new Date().toISOString(),
        kind: url.searchParams.get('kind') ?? 'report',
        bytes: raw.length,
        report: parsed,
        raw,
      }
      requests.push(entry)
      onReport(entry)
    })
    request.on('error', () => { /* client vanished; nothing to report */ })
  })

  return {
    server,
    requests,
    // Resolved against the bound address so `--port 0` (tests) reports the real one.
    get url() {
      const address = server.address()
      const actualPort = address !== null && typeof address === 'object' ? address.port : port
      return `http://${host}:${actualPort}/report`
    },
    listen: () => new Promise((resolve, reject) => {
      const onError = error => reject(error)
      server.once('error', onError)
      server.listen(port, host, () => {
        server.removeListener('error', onError)
        resolve({ port: server.address().port, host })
      })
    }),
    close: () => new Promise(resolve => server.close(() => resolve())),
  }
}

/**
 * Resolve once a report-shaped payload arrives, or time out with a reason.
 * @param {{requests: object[]}} sink
 */
export async function waitForReport(sink, options) {
  const timeoutMs = options?.timeoutMs ?? 120_000
  const accept = typeof options?.accept === 'function' ? options.accept : () => true
  const intervalMs = options?.intervalMs ?? 250
  const started = Date.now()
  for (;;) {
    const hit = sink.requests.filter(entry => accept(entry))
    if (hit.length > 0) return { ok: true, entry: hit[hit.length - 1], waitedMs: Date.now() - started }
    if (Date.now() - started >= timeoutMs) return { ok: false, waitedMs: Date.now() - started, reason: 'sink-timeout' }
    await new Promise(resolve => setTimeout(resolve, intervalMs))
  }
}

/**
 * Reassemble a report from `adb logcat` lines produced by the overlay's logcat
 * channel (`[dsh-verify] REPORT-BEGIN n bytes`, `REPORT <i> <base64>`, `REPORT-END`).
 *
 * Android WebView forwards console output to logcat, so this works without
 * `adb reverse`, USB tethering or devtools — at the cost of relying on the
 * WebView's console→logcat forwarding, which some builds disable.
 *
 * @param {string[]} lines raw logcat lines (extra log prefixes are ignored)
 * @returns {{ok: boolean, report: object|null, reason?: string, chunks?: number, bytes?: number, prefix?: string}}
 */
export function decodeLogcat(lines) {
  const text = (Array.isArray(lines) ? lines : []).join('\n')
  const begin = text.match(/REPORT-BEGIN (\d+) (\d+)/u)
  const end = /REPORT-END/u.test(text)
  if (begin === null) return { ok: false, report: null, reason: 'no-report-marker' }
  const expected = Number(begin[1])
  const bytes = Number(begin[2])
  const parts = new Map()
  for (const match of text.matchAll(/REPORT (\d+) ([A-Za-z0-9+/=]+)/gu)) {
    if (match[0].startsWith('REPORT-BEGIN') || match[0].startsWith('REPORT-END')) continue
    parts.set(Number(match[1]), match[2])
  }
  if (parts.size !== expected) return { ok: false, report: null, reason: `chunks-missing:${parts.size}/${expected}`, chunks: parts.size, bytes }
  const ordered = []
  for (let index = 0; index < expected; index += 1) {
    const chunk = parts.get(index)
    if (chunk === undefined) return { ok: false, report: null, reason: `chunk-${index}-missing`, chunks: parts.size, bytes }
    ordered.push(chunk)
  }
  let json
  try {
    json = Buffer.from(ordered.join(''), 'base64').toString('utf8')
  } catch {
    return { ok: false, report: null, reason: 'base64-invalid', chunks: parts.size, bytes }
  }
  let report
  try {
    report = JSON.parse(json)
  } catch {
    return { ok: false, report: null, reason: 'json-invalid', chunks: parts.size, bytes }
  }
  if (report?.schema !== 'dsh-device-verify/2') return { ok: false, report: null, reason: 'wrong-schema', chunks: parts.size, bytes }
  return { ok: true, report, chunks: parts.size, bytes, complete: end }
}

/** The same chunking the overlay does, so tests can round-trip it. */
export function encodeLogcatLines(report, chunkSize = 900) {
  const json = JSON.stringify(report)
  const encoded = Buffer.from(json, 'utf8').toString('base64')
  const chunks = []
  for (let index = 0; index < encoded.length; index += chunkSize) chunks.push(encoded.slice(index, index + chunkSize))
  const lines = [`[dsh-verify] REPORT-BEGIN ${chunks.length} ${json.length}`]
  chunks.forEach((chunk, index) => lines.push(`[dsh-verify] REPORT ${index} ${chunk}`))
  lines.push('[dsh-verify] REPORT-END')
  return lines
}

/** `adb reverse --list` style text → the entries that map a given tcp port. */
export function reverseMappings(text, port) {
  return String(text ?? '')
    .split('\n')
    .map(line => line.trim())
    .filter(line => line.includes(`tcp:${port}`))
}

export function formatSummary(lib, report) {
  return lib.summarize(report)
}
